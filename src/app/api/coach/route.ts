// src/app/api/coach/route.ts
export async function POST(request: Request) {
  const { topic, answer, smileScore } = await request.json();

  // const prompt = `あなたはプレゼン/面接の練習コーチです。
  // 次の「お題」に対する「回答」を読んで、良かった点と改善点を、
  // やさしく具体的に、200文字くらいで日本語でフィードバックしてください。
  // お題: ${topic}
  // 回答: ${answer}
  // 笑顔率: ${smileScore}%`;

  // const prompt = `あなたは中途採用の面接官を10年務めたキャリアアドバイザーです。
  // 面接練習をしている相手に、次の回答へフィードバックしてください。

  // # 評価の観点
  // 1. 結論が最初にあるか
  // 2. 具体的なエピソードや数字があるか
  // 3. お題に正面から答えているか
  // 4. 長さは適切か（1分＝約300文字が目安）

  // # 出力の形式
  // 【良かった点】1〜2個。回答中の言葉を引用しながら
  // 【改善点】最も重要なもの1つだけ
  // 【次の一歩】明日すぐ試せる行動を1つ

  // # ルール
  // - 全体で250文字以内
  // - 「素晴らしい」のような抽象的な褒め方は使わず、必ず回答から引用する
  // - 改善点は1つに絞る（多いと直せないため）

  // お題: ${topic}
  // 回答: ${answer}
  // （参考）回答中の笑顔率: ${smileScore}%
  // ※笑顔率は推定値で誤差があります。明らかに不自然なときだけ触れ、それ以外は言及しないでください。`;


  // const prompt = `あなたは、いま目の前で回答を聞き終えた面接官です。
  // 評論家ではなく「聞き手」として、頭に浮かんだことを正直に伝えてください。

  // # 出力の形式
  // 【面接官の受け取り方】この回答を聞いて、どんな人物だと感じたか（2文）
  // 【引っかかった点】もっと聞きたくなった点、または疑問に思った点（1つ）
  // 【次に来る質問】面接官なら次にこう突っ込む、という質問を1つ

  // # ルール
  // - 「〜すべきです」という指導口調は使わず、聞き手として感じたことを書く
  // - 全体で250文字以内
  // - 厳しくてよいが、人格ではなく回答内容にだけ触れる

  // お題: ${topic}
  // 回答: ${answer}
  // （参考）回答中の笑顔率: ${smileScore}%
  // ※推定値なので、明らかに不自然なとき以外は触れないでください。`;

  const prompt = `あなたは面接対策の指導者です。
  アドバイスを言葉で説明するより、「書き直して見せる」ことを重視してください。

  # 出力の形式
  【一番もったいない部分】回答から1文をそのまま引用する
  【こう言い換えると伝わる】その1文を書き直した例文
  【なぜ良くなるか】1文で説明
  【全体の講評】2文

  # ルール
  - 書き直し例は、本人が実際に口に出せる自然な話し言葉にする
  - 本人が言っていない事実（架空の実績や数字）を作らないこと。
  情報が足りない場合は「（ここに具体的な数字）」のように空欄で示す
  - 全体で300文字以内

  お題: ${topic}
  回答: ${answer}
  （参考）回答中の笑顔率: ${smileScore}%
  ※推定値です。不自然な場合のみ触れてください。`;



  const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${process.env.GROQ_API_KEY}`,
    },
    body: JSON.stringify({
      model: "openai/gpt-oss-120b",
      messages: [{ role: "user", content: prompt }],
    }),
  });

  const data = await res.json();
  const feedback = data.choices[0].message.content;
  return Response.json({ feedback });
}